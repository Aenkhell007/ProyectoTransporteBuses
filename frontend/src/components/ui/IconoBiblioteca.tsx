export type NombreIconoBiblioteca = keyof typeof iconos;

export function IconoBiblioteca({nombre, className = 'h-5 w-5', titulo}: {
  nombre: NombreIconoBiblioteca; className?: string; titulo?: string;
}) {
  const [width, height, , , trazos] = iconos[nombre].icon;
  return <svg viewBox={`0 0 ${width} ${height}`} fill="currentColor" focusable="false"
    className={`shrink-0 ${className}`} aria-hidden={titulo ? undefined : true}
    role={titulo ? 'img' : undefined} aria-label={titulo}>
    {titulo && <title>{titulo}</title>}
    {(Array.isArray(trazos) ? trazos : [trazos]).map((d, index) => <path key={index} d={d}/>)}
  </svg>;
}
